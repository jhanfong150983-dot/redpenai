// 節點 id 比照因材網 <code>-S<nn>
function sNodes(code: string, items: Array<[string, string]>): CurriculumNode[] {
  return items.map(([name, desc], i) => ({
    id: `${code}-S${String(i + 1).padStart(2, '0')}`,
    code, name, desc,
  }))
}

